// Converts the world-editor export (src/game/world/authored/career.map.json) into the five
// artifacts the game consumes. Requires the paid Cute Fantasy pack unpacked at
// public/game/cute-fantasy/ (gitignored) — this cannot run in CI.
//
// Run: node scripts/import-map.mjs (npm run map:import), then npm run assets:pack.
//
// Deterministic: no Date.now/Math.random, and convert.js sorts every collection it emits.

import path from 'node:path'
import fs from 'node:fs/promises'
import { existsSync } from 'node:fs'
import sharp from 'sharp'
import { convertMap, slugFor, doorCoverage } from '../src/game/world/authored/convert.js'
import { interiorIdOf, validateInterior, interiorData, interiorCoverage } from '../src/game/world/authored/interior.js'

const ROOT = process.cwd()
const IN_MAP = path.join(ROOT, 'src', 'game', 'world', 'authored', 'career.map.json')
const IN_EXPERIENCE = path.join(ROOT, 'src', 'data', 'experience.json')
const OUT_MANIFEST = path.join(ROOT, 'src', 'game', 'assets', 'manifest.authored.js')
const OUT_TILES = path.join(ROOT, 'src', 'game', 'world', 'authored', 'career.tiles.json')
const OUT_PLACEMENTS = path.join(ROOT, 'src', 'data', 'placements.json')
const OUT_CLIPS = path.join(ROOT, 'src', 'data', 'clips.json')
const OUT_INTERACTABLES = path.join(ROOT, 'src', 'data', 'interactables.json')
const IN_INTERIORS = path.join(ROOT, 'src', 'game', 'world', 'authored', 'interiors')
const OUT_INTERIOR_DATA = path.join(ROOT, 'src', 'data', 'interiors')
const OUT_INTERIOR_PNG = path.join(ROOT, 'public', 'game', 'interiors')
const PACK = path.join(ROOT, 'public', 'game', 'cute-fantasy')

const PACK_ROOT = 'Cute_Fantasy/'
const diskPath = p => path.join(PACK, p.startsWith(PACK_ROOT) ? p.slice(PACK_ROOT.length) : p)

async function dimsCache(map) {
  const paths = new Set()
  for (const l of map.layers) {
    // A sprite-less marker (docs/adr/0006) has no frame and nothing to measure.
    if (l.type === 'objects') for (const o of l.objects || []) { if (o.frame) paths.add(o.frame.slice(0, o.frame.lastIndexOf('#'))) }
    else for (const c of l.cells || []) paths.add(c.frame.slice(0, c.frame.lastIndexOf('#')))
  }
  // Clip frames too: a sheet reached ONLY through a clip's later frames would measure 0x0 here
  // and convert.js would refuse a perfectly good map on the bounds check.
  for (const c of map.clips || []) {
    for (const f of c.frames || []) paths.add(f.slice(0, f.lastIndexOf('#')))
  }
  const dims = {}
  for (const p of [...paths].sort()) {
    if (!existsSync(diskPath(p))) continue
    const meta = await sharp(diskPath(p)).metadata()
    dims[p] = { w: meta.width, h: meta.height }
  }
  return dims
}

// Keys AUTHORED_IMAGE_SIZE the same way AUTHORED_IMAGES is keyed (slugFor(path)), so
// manifest.test.js can merge it straight into REAL_IMAGE_SIZE without a lookup table.
function imageSizeOf(manifest, dims) {
  const bySlug = {}
  for (const [p, s] of Object.entries(dims)) bySlug[slugFor(p)] = s
  const size = {}
  for (const key of Object.keys(manifest.images).sort()) {
    if (bySlug[key]) size[key] = bySlug[key]
  }
  return size
}

function manifestModule(manifest, imageSize) {
  const j = v => JSON.stringify(v, null, 2)
  return `// GENERATED by scripts/import-map.mjs — do not edit by hand.
// Frames sliced out of the authored map (src/game/world/authored/career.map.json).

export const AUTHORED_IMAGES = ${j(manifest.images)}

export const AUTHORED_FRAMES = ${j(manifest.frames)}

// Real pixel dimensions of each source PNG (sharp-measured at import time), keyed the same way
// as AUTHORED_IMAGES — merge into manifest.test.js's REAL_IMAGE_SIZE to keep the bounds check
// enforced for the authored namespace without hand-maintaining it.
export const AUTHORED_IMAGE_SIZE = ${j(imageSize)}
`
}

const json = v => `${JSON.stringify(v, null, 2)}\n`

async function interiorFiles() {
  const files = await fs.readdir(IN_INTERIORS).catch(() => [])
  return files.filter(f => interiorIdOf(f)).sort()
}

async function importInterior(file, { entryById, exteriorDoorIds }) {
  const id = interiorIdOf(file)
  const map = JSON.parse(await fs.readFile(path.join(IN_INTERIORS, file), 'utf8'))
  const dims = await dimsCache(map)
  const out = convertMap(map, { dimsOf: p => dims[p] || { w: 0, h: 0 }, exists: p => existsSync(diskPath(p)), interior: true })
  validateInterior(id, out.interactables, entryById[id], exteriorDoorIds)
  await fs.mkdir(OUT_INTERIOR_DATA, { recursive: true })
  await fs.writeFile(path.join(OUT_INTERIOR_DATA, `${id}.json`), json(interiorData(out)))
  await fs.writeFile(path.join(IN_INTERIORS, `${id}.manifest.json`), json(out.manifest))
  return id
}

// A removed interior must close its house: the generated files are what say it is open. The
// hand-drawn *.map.json is the source and is never touched.
async function removeStale(dir, suffixes, ids) {
  const files = await fs.readdir(dir).catch(() => [])
  for (const f of files) {
    const suffix = suffixes.find(s => f.endsWith(s))
    if (suffix && !ids.includes(f.slice(0, -suffix.length))) await fs.rm(path.join(dir, f))
  }
}

async function importInteriors(experience, exteriorOut) {
  const exteriorDoorIds = exteriorOut.interactables.filter(e => e.kind === 'door').map(e => e.id)
  const entryById = Object.fromEntries((experience.entries || []).filter(e => e.id).map(e => [e.id, e]))
  const ids = []
  for (const file of await interiorFiles()) ids.push(await importInterior(file, { entryById, exteriorDoorIds }))
  await removeStale(OUT_INTERIOR_DATA, ['.atlas.json', '.json'], ids)
  await removeStale(IN_INTERIORS, ['.manifest.json'], ids)
  await removeStale(OUT_INTERIOR_PNG, ['.png'], ids)
  console.log(interiorCoverage(ids, exteriorDoorIds))
}

async function main() {
  const map = JSON.parse(await fs.readFile(IN_MAP, 'utf8'))
  const dims = await dimsCache(map)
  // The visible CV entries, so a `door:` tag naming a job that does not exist fails here rather
  // than silently never matching at runtime (docs/adr/0001).
  const experience = JSON.parse(await fs.readFile(IN_EXPERIENCE, 'utf8'))
  const experienceIds = (experience.entries || [])
    .filter(e => e.visible !== false && e.id)
    .map(e => e.id)
  const out = convertMap(map, {
    dimsOf: p => dims[p] || { w: 0, h: 0 },
    exists: p => existsSync(diskPath(p)),
    experienceIds,
  })
  const imageSize = imageSizeOf(out.manifest, dims)
  await fs.writeFile(OUT_MANIFEST, manifestModule(out.manifest, imageSize))
  await fs.writeFile(OUT_TILES, `${JSON.stringify(out.tiles, null, 2)}\n`)
  await fs.writeFile(OUT_PLACEMENTS, `${JSON.stringify(out.placements, null, 2)}\n`)
  await fs.writeFile(OUT_CLIPS, `${JSON.stringify(out.clips, null, 2)}\n`)
  await fs.writeFile(OUT_INTERACTABLES, `${JSON.stringify(out.interactables, null, 2)}\n`)
  const cells = out.tiles.layers.reduce((n, l) => n + l.cells.length, 0)
  console.log(`imported: ${Object.keys(out.manifest.frames).length} frames, ${cells} cells, `
    + `${out.placements.length} placements, ${Object.keys(out.clips).length} clips, `
    + `${Object.keys(out.tiles.anchors).length} anchors, ${out.interactables.length} interactables`)
  // validateMap has already refused a missing or dead door; this line is the receipt.
  const cov = doorCoverage(out.interactables, experienceIds)
  console.log(`authored houses: ${cov.authored.length} of ${experienceIds.length} experiences`)
  await importInteriors(experience, out)
}

main().catch(e => { console.error(e.message); process.exit(1) })
